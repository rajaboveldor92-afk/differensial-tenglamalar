#!/usr/bin/env bash
# Builds the APK without Gradle, using Android SDK command-line tools:
#   aapt2 (resources), javac --release 8 + d8 (code), zipalign, apksigner.
# Requirements:
#   JDK 17+, Android SDK platform 36 and build-tools 36.0.0.
# Install SDK pieces with:
#   sdkmanager "platforms;android-36" "build-tools;36.0.0"
#
# Usage:
#   android/build.sh                 test build, signed with a local TEST key (created on first run, kept outside the repo)
#   KEYSTORE=/path/release.jks KEY_ALIAS=dt KEYSTORE_PASS=... KEY_PASS=... android/build.sh release
# The signing key is never stored in the source tree.
set -euo pipefail

MODE="${1:-test}"
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/.." && pwd)"
SDK_ROOT="${ANDROID_SDK_ROOT:-${ANDROID_HOME:-$HOME/Android/Sdk}}"
PLATFORM_API="${ANDROID_PLATFORM_API:-36}"
BUILD_TOOLS_VERSION="${ANDROID_BUILD_TOOLS_VERSION:-36.0.0}"
ANDROID_JAR="${ANDROID_JAR:-$SDK_ROOT/platforms/android-$PLATFORM_API/android.jar}"

resolve_tool() {
  local name="$1" preferred="$2" found=""
  if [ -x "$preferred" ]; then
    printf '%s\n' "$preferred"
    return 0
  fi
  found="$(command -v "$name" 2>/dev/null || true)"
  if [ -n "$found" ]; then
    printf '%s\n' "$found"
    return 0
  fi
  echo "Missing Android build tool '$name'. Install build-tools;$BUILD_TOOLS_VERSION or set ANDROID_SDK_ROOT." >&2
  return 1
}

[ -f "$ANDROID_JAR" ] || {
  echo "Missing Android API $PLATFORM_API platform: $ANDROID_JAR" >&2
  echo "Run: sdkmanager \"platforms;android-$PLATFORM_API\" \"build-tools;$BUILD_TOOLS_VERSION\"" >&2
  exit 1
}

AAPT2="${AAPT2:-$(resolve_tool aapt2 "$SDK_ROOT/build-tools/$BUILD_TOOLS_VERSION/aapt2")}" 
D8="${D8:-$(resolve_tool d8 "$SDK_ROOT/build-tools/$BUILD_TOOLS_VERSION/d8")}" 
ZIPALIGN="${ZIPALIGN:-$(resolve_tool zipalign "$SDK_ROOT/build-tools/$BUILD_TOOLS_VERSION/zipalign")}" 
APKSIGNER="${APKSIGNER:-$(resolve_tool apksigner "$SDK_ROOT/build-tools/$BUILD_TOOLS_VERSION/apksigner")}" 

VERSION_NAME="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$HERE/AndroidManifest.xml")"
VERSION_CODE="$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' "$HERE/AndroidManifest.xml")"
OUT="$ROOT/build/apk"; rm -rf "$OUT"; mkdir -p "$OUT"/{assets,gen,classes,res-flat,dex}
export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:-}"

echo "== 1/6 assets (offline web app)"
mkdir -p "$OUT/assets/web"
( cd "$ROOT/web" && tar --exclude='./slide.html' --exclude='./video/*-720.mp4' -cf - . ) | ( cd "$OUT/assets/web" && tar -xf - )
# sanity: the app must not contain secrets
if grep -rIl -E 'sk-ant-[A-Za-z0-9_-]{10,}|ANTHROPIC_API_KEY=.+' "$OUT/assets" >/dev/null 2>&1; then echo "secret-looking string found in assets" >&2; exit 1; fi

echo "== 2/6 resources (compile/target API $PLATFORM_API)"
"$AAPT2" compile --dir "$HERE/res" -o "$OUT/res-flat/res.zip"
"$AAPT2" link -I "$ANDROID_JAR" --manifest "$HERE/AndroidManifest.xml" -A "$OUT/assets" \
  --min-sdk-version 24 --target-sdk-version "$PLATFORM_API" --version-code "$VERSION_CODE" --version-name "$VERSION_NAME" \
  -0 mp4 -0 woff2 -0 png --java "$OUT/gen" -o "$OUT/base.apk" "$OUT/res-flat/res.zip"

echo "== 3/6 java"
DEBUG=true; [ "$MODE" = release ] && DEBUG=false
mkdir -p "$OUT/gen/uz/cyber/dt"
printf 'package uz.cyber.dt;\n/** Generated by build.sh */\nfinal class BuildConfigLite { static final boolean DEBUG = %s; private BuildConfigLite() {} }\n' "$DEBUG" > "$OUT/gen/uz/cyber/dt/BuildConfigLite.java"
set +e
javac -nowarn --release 8 -encoding UTF-8 -cp "$ANDROID_JAR" -d "$OUT/classes" $(find "$HERE/src" "$OUT/gen" -name '*.java') 2>"$OUT/javac.err"
JAVAC_STATUS=$?
set -e
grep -v 'JAVA_TOOL_OPTIONS' "$OUT/javac.err" >&2 || true
[ "$JAVAC_STATUS" -eq 0 ] || { echo "javac failed" >&2; exit "$JAVAC_STATUS"; }
[ -f "$OUT/classes/uz/cyber/dt/MainActivity.class" ] || { echo "javac did not produce MainActivity.class" >&2; exit 1; }

echo "== 4/6 dex (D8)"
jar --create --file "$OUT/classes.jar" -C "$OUT/classes" .
"$D8" --min-api 24 --lib "$ANDROID_JAR" --output "$OUT/dex" "$OUT/classes.jar"
[ -f "$OUT/dex/classes.dex" ] || { echo "D8 failed" >&2; exit 1; }
cp "$OUT/base.apk" "$OUT/unsigned.apk"
cp "$OUT/dex/classes.dex" "$OUT/classes.dex"
( cd "$OUT" && zip -q -X unsigned.apk classes.dex )

echo "== 5/6 align"
"$ZIPALIGN" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

echo "== 6/6 sign ($MODE)"
if [ "$MODE" = release ]; then
  : "${KEYSTORE:?set KEYSTORE}" "${KEY_ALIAS:?set KEY_ALIAS}" "${KEYSTORE_PASS:?set KEYSTORE_PASS}"
  KEY_PASS="${KEY_PASS:-$KEYSTORE_PASS}"
  NAME="differensial-tenglamalar-$VERSION_NAME-release.apk"
else
  KEYDIR="${TEST_KEY_DIR:-$HOME/.dt-test-key}"; mkdir -p "$KEYDIR"; chmod 700 "$KEYDIR"
  KEYSTORE="$KEYDIR/test.jks"; KEY_ALIAS=dt-test
  if [ ! -f "$KEYDIR/pass" ]; then head -c 18 /dev/urandom | base64 | tr -d '/+=' > "$KEYDIR/pass"; chmod 600 "$KEYDIR/pass"; fi
  KEYSTORE_PASS="$(cat "$KEYDIR/pass")"; KEY_PASS="$KEYSTORE_PASS"
  if [ ! -f "$KEYSTORE" ]; then
    keytool -genkeypair -keystore "$KEYSTORE" -storepass "$KEYSTORE_PASS" -keypass "$KEY_PASS" -alias "$KEY_ALIAS" \
      -keyalg RSA -keysize 3072 -validity 10000 -dname "CN=DT test build, O=Test, C=UZ" 2>&1 | grep -v JAVA_TOOL_OPTIONS || true
  fi
  NAME="differensial-tenglamalar-$VERSION_NAME-test.apk"
fi
mkdir -p "$ROOT/dist"
"$APKSIGNER" sign --ks "$KEYSTORE" --ks-key-alias "$KEY_ALIAS" --ks-pass "pass:$KEYSTORE_PASS" --key-pass "pass:$KEY_PASS" \
  --min-sdk-version 24 --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
  --out "$ROOT/dist/$NAME" "$OUT/aligned.apk" 2>&1 | grep -v JAVA_TOOL_OPTIONS || true
"$APKSIGNER" verify --verbose "$ROOT/dist/$NAME" 2>&1 | grep -E 'Verifies|v[123] scheme' | grep -v JAVA_TOOL_OPTIONS
ls -la "$ROOT/dist/$NAME"
sha256sum "$ROOT/dist/$NAME"
