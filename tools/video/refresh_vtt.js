// Rewrites the subtitle files of a pack set that no longer match the scripts, using the player's own cue code
// (web/js/video.js) and web/video/index.js, then updates their sizes and SHA-256 in manifest.json and index.js.
// Needed when a script line changes in one language: videos narrated in the other languages keep their
// timing, but their subtitles in the changed language must show the new text.
// Usage: node tools/video/refresh_vtt.js <pack-dir>
const fs = require('fs'), vm = require('vm'), path = require('path'), crypto = require('crypto');
const dir = process.argv[2];
const root = path.join(__dirname, '../..'), indexFile = path.join(root, 'web/video/index.js');
const ctx = { window: {}, console, Math, document: { addEventListener() {} } }; ctx.window.DT = { views: {} }; ctx.DT = ctx.window.DT; vm.createContext(ctx);
const src = fs.readFileSync(path.join(root, 'web/js/video.js'), 'utf8');
vm.runInContext('(function(){' + src.slice(src.indexOf('function splitSentences'), src.indexOf('/* ---------- slide renderer')) + ';DT.__cues = cues;})()', ctx);
vm.runInContext(fs.readFileSync(indexFile, 'utf8'), ctx);
const scripts = JSON.parse(require('child_process').execFileSync('node', [path.join(__dirname, 'dump.js')], { maxBuffer: 1 << 26 }));
const M = ctx.DT.VIDEO_MEDIA, changed = {};
// build.py and the player round times separately, so cues 1 ms apart count as equal
const parse = s => [...s.matchAll(/^([\d:.]+) --> ([\d:.]+)\n(.*)$/gm)].map(m => [m[1], m[2], m[3]]);
const secs = t => t.split(':').reduce((a, x) => a * 60 + parseFloat(x), 0);
const same = (a, b) => { const x = parse(a), y = parse(b); return x.length === y.length && x.every((c, i) => c[2] === y[i][2] && Math.abs(secs(c[0]) - secs(y[i][0])) <= 0.002 && Math.abs(secs(c[1]) - secs(y[i][1])) <= 0.002); };
for (const t of Object.keys(scripts)) for (const part of scripts[t].parts) for (const al of ['uz', 'ru', 'en']) for (const sl of ['uz', 'ru', 'en']) {
  const name = `${part.id}-${al}-sub-${sl}.vtt`, f = path.join(dir, name);
  if (!fs.existsSync(f) || !M.parts[part.id] || !M.parts[part.id][al]) continue;
  const want = ctx.DT.toVTT(ctx.DT.__cues(part, M.parts[part.id][al], sl, al));
  if (same(fs.readFileSync(f, 'utf8'), want)) continue;
  fs.writeFileSync(f, want);
  changed[name] = { bytes: Buffer.byteLength(want), sha256: crypto.createHash('sha256').update(want).digest('hex') };
  console.log('rewrote', name);
}
for (const p of M.packs) for (const f of p.files) if (changed[f.name]) { Object.assign(f, changed[f.name]); }
for (const p of M.packs) p.bytes = p.files.reduce((s, f) => s + f.bytes, 0);
fs.writeFileSync(indexFile, '/* Generated by tools/video/merge_packs.py — do not edit. */\nDT.VIDEO_MEDIA = ' + JSON.stringify(M) + ';\n');
fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(M, null, 1));
console.log(Object.keys(changed).length, 'subtitle files rewritten');
