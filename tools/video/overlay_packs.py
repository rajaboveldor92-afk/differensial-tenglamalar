#!/usr/bin/env python3
"""Replaces some topic × narration-language packs of an existing merged pack set with re-rendered ones.

<base> is a folder written by merge_packs.py (flat pack files + manifest.json). Every folder under
<artifacts> that holds a manifest.json from tools/video/build.py contributes the packs it actually
produced; those replace the base packs with the same topic, language and quality, together with
that language's part timings. Files are checked against their SHA-256, files no pack uses any more
are removed, and manifest.json and web/video/index.js are rewritten.

Usage: python3 tools/video/overlay_packs.py <base-dir> <artifacts-dir> [--bundle t01]
"""
import argparse, json, os, re, shutil, sys

from merge_packs import ROOT, sha


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('base')
    ap.add_argument('artifacts')
    ap.add_argument('--bundle', default='t01')
    a = ap.parse_args()
    bundle = set(filter(None, a.bundle.split(',')))
    index = json.load(open(os.path.join(a.base, 'manifest.json')))
    packs = {(p['topic'], p['lang'], p['q']): p for p in index['packs']}
    replaced = set()
    for dirpath, _, files in sorted(os.walk(a.artifacts)):
        if 'manifest.json' not in files:
            continue
        m = json.load(open(os.path.join(dirpath, 'manifest.json')))
        for p in m['packs']:
            if not all(os.path.exists(os.path.join(dirpath, x['name'])) for x in p['files']):
                continue  # entries carried over from older builds, not produced in this folder
            key = (p['topic'], p['lang'], p['q'])
            if key in replaced:
                sys.exit('duplicate pack %s in %s' % (p['id'], dirpath))
            if key not in packs:
                sys.exit('pack %s is not in the base set' % p['id'])
            replaced.add(key)
            for f in p['files']:
                src = os.path.join(dirpath, f['name'])
                if os.path.getsize(src) != f['bytes'] or sha(src) != f['sha256']:
                    sys.exit('checksum mismatch: ' + src)
                shutil.copy(src, os.path.join(a.base, f['name']))
            packs[key] = dict(p, bundled=p['topic'] in bundle and p['q'] == '480')
            for name in (f['name'] for f in p['files']):
                mm = re.match(r'(.+)-(uz|ru|en)-(480|720)\.mp4$', name)
                if mm:
                    index['parts'][mm.group(1)][mm.group(2)] = m['parts'][mm.group(1)][mm.group(2)]
            print('replaced', p['id'], 'from', dirpath)
    if not replaced:
        sys.exit('no packs found under ' + a.artifacts)
    index['packs'] = sorted(packs.values(), key=lambda p: (p['topic'], p['lang'], p['q']))
    used = {f['name'] for p in index['packs'] for f in p['files']} | {'manifest.json'}
    for f in os.listdir(a.base):
        if f not in used:
            os.remove(os.path.join(a.base, f))
            print('removed unused', f)
    vdir = os.path.join(ROOT, 'web', 'video')
    for f in os.listdir(vdir):
        if f.endswith('.mp4'):
            os.remove(os.path.join(vdir, f))
    for p in index['packs']:
        if p['bundled']:
            for f in p['files']:
                if f['name'].endswith('.mp4'):
                    shutil.copy(os.path.join(a.base, f['name']), os.path.join(vdir, f['name']))
    with open(os.path.join(vdir, 'index.js'), 'w') as f:
        f.write('/* Generated by tools/video/merge_packs.py — do not edit. */\nDT.VIDEO_MEDIA = ' + json.dumps(index, ensure_ascii=False, separators=(',', ':')) + ';\n')
    json.dump(index, open(os.path.join(a.base, 'manifest.json'), 'w'), ensure_ascii=False, indent=1)
    print('replaced', len(replaced), 'packs; total', len(index['packs']))


if __name__ == '__main__':
    main()
