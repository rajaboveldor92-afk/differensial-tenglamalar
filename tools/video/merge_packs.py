#!/usr/bin/env python3
"""Merges per-topic video build outputs (the CI artifacts of rebuild-revised-videos.yml) into one pack set.

Each input folder holds the files tools/video/build.py wrote for one topic and some narration languages,
plus its manifest.json. Only that topic's parts and packs are taken from each manifest, every file is
checked against its SHA-256, and the result is written as:
  <out>/            all pack files (flat) + manifest.json   -> upload to the video server or zip per pack
  web/video/index.js                                         -> timings + pack list used by the app
  web/video/<part>-<lang>-480.mp4 for --bundle topics       -> shipped inside the APK

Usage: python3 tools/video/merge_packs.py <artifacts-dir> <out-dir> [--bundle t01] [--voice "..."]
"""
import argparse, hashlib, json, os, re, shutil, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('artifacts')
    ap.add_argument('out')
    ap.add_argument('--bundle', default='t01')
    ap.add_argument('--voice', default='')
    a = ap.parse_args()
    bundle = set(filter(None, a.bundle.split(',')))
    os.makedirs(a.out, exist_ok=True)
    index = {'parts': {}, 'packs': []}
    seen = set()
    for dirpath, _, files in sorted(os.walk(a.artifacts)):
        if 'manifest.json' not in files:
            continue
        m = json.load(open(os.path.join(dirpath, 'manifest.json')))
        mp4s = [f for f in files if f.endswith('.mp4')]
        topics = {p['topic'] for p in m['packs'] if all(os.path.exists(os.path.join(dirpath, x['name'])) for x in p['files'])}
        for p in m['packs']:
            if p['topic'] not in topics or not all(os.path.exists(os.path.join(dirpath, x['name'])) for x in p['files']):
                continue  # entries carried over from older builds, not produced in this folder
            key = (p['topic'], p['lang'], p['q'])
            if key in seen:
                sys.exit('duplicate pack %s in %s' % (p['id'], dirpath))
            seen.add(key)
            for f in p['files']:
                src = os.path.join(dirpath, f['name'])
                if os.path.getsize(src) != f['bytes'] or sha(src) != f['sha256']:
                    sys.exit('checksum mismatch: ' + src)
                dst = os.path.join(a.out, f['name'])
                if os.path.exists(dst) and sha(dst) != f['sha256']:
                    sys.exit('two different files named ' + f['name'])
                shutil.copy(src, dst)
            p = dict(p, bundled=p['topic'] in bundle and p['q'] == '480')
            index['packs'].append(p)
            for name in (f['name'] for f in p['files']):
                mm = re.match(r'(.+)-(uz|ru|en)-(480|720)\.mp4$', name)
                if mm:
                    pid, lang = mm.group(1), mm.group(2)
                    index['parts'].setdefault(pid, {})[lang] = m['parts'][pid][lang]
        print('merged', dirpath, sorted(topics), len(mp4s), 'mp4')
    index['packs'].sort(key=lambda p: (p['topic'], p['lang'], p['q']))
    index['voice'] = a.voice or 'synthetic'
    # bundled videos go inside the APK; old bundled files are replaced
    vdir = os.path.join(ROOT, 'web', 'video')
    for f in os.listdir(vdir):
        if f.endswith('.mp4'):
            os.remove(os.path.join(vdir, f))
    for p in index['packs']:
        if p['bundled']:
            for f in p['files']:
                if f['name'].endswith('.mp4'):
                    shutil.copy(os.path.join(a.out, f['name']), os.path.join(vdir, f['name']))
    with open(os.path.join(vdir, 'index.js'), 'w') as f:
        f.write('/* Generated by tools/video/merge_packs.py — do not edit. */\nDT.VIDEO_MEDIA = ' + json.dumps(index, ensure_ascii=False, separators=(',', ':')) + ';\n')
    json.dump(index, open(os.path.join(a.out, 'manifest.json'), 'w'), ensure_ascii=False, indent=1)
    langs = sorted({p['lang'] for p in index['packs']}); tops = sorted({p['topic'] for p in index['packs']})
    print('packs', len(index['packs']), 'topics', len(tops), 'langs', langs, 'parts', len(index['parts']),
          'bytes', sum(p['bytes'] for p in index['packs']))
    missing = [(t, l, q) for t in tops for l in ['uz', 'ru', 'en'] for q in ['480', '720'] if (t, l, q) not in seen]
    if missing:
        sys.exit('missing packs: %s' % missing)


if __name__ == '__main__':
    main()
